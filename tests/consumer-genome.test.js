const headers = {
  '23andMe':
    '# This data file is generated by 23andMe.\n# reference assembly build 37; plus strand\n# rsid\tchromosome\tposition\tgenotype\n',
  AncestryDNA:
    '#AncestryDNA raw data download\n# human reference build 37.1; forward strand\nrsid\tchromosome\tposition\tallele1\tallele2\n',
};
const row = {
  citation: 'C1',
  rowNumber: 2,
  chrom: '2',
  pos: 21231592,
  ref: 'G',
  alt: 'A',
  gene: 'APOB',
  sig: 'C',
  gnomadkey: '2-21008720-G-A',
};
const lookup = {
  schema: 1,
  build: 'GRCh37',
  catalog: { rs6413458: ['2:21231592:G:A'] },
  markers: {},
  aliases: { rs9: 'rs6413458' },
  sources: { catalog: { sha256: 'a'.repeat(64) } },
};
const line = (provider, id, chrom, pos, gt) =>
  [id, chrom, pos, ...(provider === '23andMe' ? [gt] : [...gt])].join('\t');
const fileFor = (provider, rows, build = 'GRCh37') =>
  new File(
    [headers[provider].replace('37', build === 'GRCh38' ? '38' : '37'), rows.join('\n')],
    'SYNTHETIC-DNA.txt',
  );
async function match(file, candidates = [row], reference = lookup) {
  const genome = await identifyGenome(file);
  const result = await matchGenomeSource({
    file,
    genome,
    candidates,
    lookup: reference,
    fetchImpl: () => {
      throw new Error('A selected file must never be fetched or uploaded');
    },
  });
  return { genome, result };
}

test('both original provider formats work as TXT, gzip and ZIP; headers determine provider/build', async () => {
  for (const provider of Object.keys(headers)) {
    const input = fileFor(provider, [line(provider, 'rs6413458', '2', 21231592, 'GA')]);
    const text = '\uFEFF' + (await input.text()).replaceAll('\n', '\r\n');
    const bytes = strToU8(text);
    for (const [name, content] of [
      ['synthetic.txt', bytes],
      ['synthetic.txt.gz', gzipSync(bytes)],
      [
        'synthetic.zip',
        zipSync({ 'README.txt': strToU8('Synthetic test only.'), 'dna.txt': bytes }),
      ],
    ]) {
      const file = new File([content], name);
      assert.equal(chooseGenomeFile([file]), file);
      const { genome, result } = await match(file);
      assert.equal(genome.provider, provider);
      assert.equal(genome.build, 'GRCh37');
      assert.equal(genome.sha256, createHash('sha256').update(content).digest('hex'));
      assert.equal(result.matches.length, 1);
      assert.deepEqual(result.matches[0].call.alleles, ['G', 'A']);
      assert.equal(result.matches[0].call.copies, 1);
      assert.equal(
        result.matches[0].call.filter,
        undefined,
        'Do not invent PASS or sequencing quality for array calls',
      );
      const evidence = compactMatch(result.matches[0]);
      assert.match(evidence.variant, /21,231,592 in the GRCh37/);
      assert.equal(
        evidence.sources.gnomAD,
        'https://gnomad.broadinstitute.org/variant/2-21008720-G-A?dataset=gnomad_r4',
      );
    }
  }
});

test('Genomewalk SNP rules: no-calls, partials, I/D, haploid, sex chromosomes, wrong alleles and conflicting sites stay out', async () => {
  for (const provider of Object.keys(headers)) {
    for (const gt of ['--', '00', 'NN', 'A-', 'I/D'.replace('/', ''), 'GG', 'AC']) {
      const { result } = await match(
        fileFor(provider, [line(provider, 'rs6413458', '2', 21231592, gt)]),
      );
      assert.equal(result.matches.length, 0, `${provider} ${gt}`);
    }
    for (const calls of [
      ['GA', 'GG'],
      ['GA', '--'],
      ['GA', 'ID'],
    ]) {
      const { result } = await match(
        fileFor(
          provider,
          calls.map((gt) => line(provider, 'rs6413458', '2', 21231592, gt)),
        ),
      );
      assert.equal(result.matches.length, 0);
      assert.equal(result.issues.length, 1);
    }
    const { result } = await match(
      fileFor(
        provider,
        ['GA', 'AG'].map((gt) => line(provider, 'rs6413458', '2', 21231592, gt)),
      ),
    );
    assert.equal(result.matches.length, 1);
    assert.equal(result.matches[0].recordCount, 2);
    for (const chrom of [
      'X',
      'Y',
      'MT',
      ...(provider === 'AncestryDNA' ? ['23', '24', '25', '26'] : []),
    ]) {
      const file = fileFor(provider, [line(provider, 'i1', chrom, 100, 'GA')]);
      assert.equal((await match(file, [{ ...row, chrom, pos: 100 }])).result.matches.length, 0);
    }
  }
  assert.equal(
    (await match(fileFor('23andMe', [line('23andMe', 'rs6413458', '2', 21231592, 'A')]))).result
      .matches.length,
    0,
  );
  assert.equal(
    (
      await match(fileFor('23andMe', [line('23andMe', 'rs6413458', '2', 21231592, 'GA')]), [
        { ...row, alt: 'AG' },
      ])
    ).result.matches.length,
    0,
  );
});

test('coordinates remain authoritative, known rsID locations check agreement, aliases work; no allele strand flipping', async () => {
  for (const id of ['rs6413458', 'rs9', 'i123', 'rs123456']) {
    assert.equal(
      (await match(fileFor('23andMe', [line('23andMe', id, '2', 21231592, 'AA')]))).result
        .matches[0].call.copies,
      2,
    );
  }
  const relocated = { ...row, pos: 21231593 };
  const { result } = await match(
    fileFor('23andMe', [line('23andMe', 'rs6413458', '2', relocated.pos, 'GA')]),
    [relocated],
  );
  assert.equal(result.matches.length, 0);
  assert.equal(result.stats.rsidLocationMismatches, 1);
  assert.equal(
    (await match(fileFor('23andMe', [line('23andMe', 'rs6413458', '2', 21231592, 'CT')]))).result
      .matches.length,
    0,
  );
  await assert.rejects(
    match(fileFor('23andMe', [line('23andMe', 'rs6413458', '2', 21231592, 'GA')]), [row], {
      ...lookup,
      build: 'GRCh38',
    }),
    /genome build/,
  );
});

test('build validation and documented Ancestry defaults never override explicit unsupported or conflicting metadata', async () => {
  for (const provider of Object.keys(headers)) {
    const file = fileFor(provider, [line(provider, 'rs1', '1', 100, 'CT')]);
    const original = await file.text();
    for (const text of [
      original.replaceAll('37', '36'),
      original.replaceAll('37', 'unknown'),
      original.replace('strand', 'strand\n# build 38'),
      original.replace(/(?:plus|forward) strand/, 'reverse strand'),
      original.replace(provider, 'UnsupportedProvider'),
    ]) {
      await assert.rejects(identifyGenome(new File([text], 'raw.txt')));
    }
    assert.equal(
      (await identifyGenome(fileFor(provider, [line(provider, 'rs1', '1', 100, 'CT')], 'GRCh38')))
        .build,
      'GRCh38',
    );
  }
  const a = new File(
    ['# AncestryDNA\nrsid\tchromosome\tposition\tallele1\tallele2\nrs1\t1\t100\tC\tT'],
    'raw.txt',
  );
  assert.equal((await identifyGenome(a)).buildSource, 'documented AncestryDNA format');
  await assert.rejects(
    identifyGenome(
      new File(['# 23andMe\n# rsid\tchromosome\tposition\tgenotype\nrs1\t1\t100\tCT'], 'raw.txt'),
    ),
    /build/,
  );
});

test('damaged archives, ambiguous payloads, unsupported formats, late malformed rows and cancellation produce no matches', async () => {
  const f = fileFor('23andMe', [line('23andMe', 'rs6413458', '2', 21231592, 'GA')]);
  const bytes = new Uint8Array(await f.arrayBuffer());
  const gz = gzipSync(bytes);
  const corrupt = gz.slice();
  corrupt[corrupt.length - 8] ^= 1;
  const zip = zipSync({ 'dna.txt': bytes });
  for (const [name, content] of [
    ['broken.txt.gz', corrupt],
    ['broken.zip', zip.slice(0, -10)],
    ['multiple.zip', zipSync({ 'one.txt': bytes, 'two.txt': bytes })],
    ['empty.txt', ''],
    ['false.txt', 'not DNA'],
  ]) {
    await assert.rejects(identifyGenome(new File([content], name)));
  }
  for (const name of ['dna.csv.gz', 'dna.bam', 'raw.txt.tbi'])
    assert.throws(() => chooseGenomeFile([{ name }]), /Choose one/);
  assert.throws(() => chooseGenomeFile([f, f]), /Choose one/);
  const invalid = new File([bytes, '\nrs2\t1\tbroken\tCT'], 'late.txt');
  await assert.rejects(match(invalid));
  await assert.rejects(identifyGenome(f, { signal: AbortSignal.abort() }), { name: 'AbortError' });
  const genome = await identifyGenome(f);
  await assert.rejects(
    matchGenomeSource({ genome, file: f, lookup, signal: AbortSignal.abort() }),
    { name: 'AbortError' },
  );
  const altered = new File([(await f.text()).replace('GA', 'AA')], f.name);
  await assert.rejects(
    matchGenomeSource({ genome, file: altered, lookup, candidates: [row] }),
    /integrity/,
  );
});

test('raw-DNA cache identity includes build, format and lookup revision; GRCh37 evidence survives storage', async () => {
  const { genome, result } = await match(
    fileFor('23andMe', [line('23andMe', 'rs6413458', '2', 21231592, 'GA')]),
  );
  const config = {
    localGenome: genome,
    catalog: {
      phase: 'ready',
      rows: 1,
      sha256: 'a'.repeat(64),
      cacheKey: 'catalog',
      lookupRevision: 'lookup',
    },
  };
  const key = matchCacheIdentity(config);
  for (const changed of [
    { ...config, localGenome: { ...genome, build: 'GRCh38' } },
    { ...config, localGenome: { ...genome, format: 'vcf' } },
    { ...config, catalog: { ...config.catalog, lookupRevision: 'new' } },
  ])
    assert.notEqual(matchCacheIdentity(changed), key);
  const memory = new Map();
  const cache = new MatchCache(() => ({
    getItem: (k) => memory.get(k) ?? null,
    setItem: (k, v) => memory.set(k, v),
    removeItem: (k) => memory.delete(k),
  }));
  assert.equal(
    cache.write(key, {
      total: 1,
      source: { build: 'GRCh37', sha256: config.catalog.sha256 },
      result,
    }).status,
    'saved',
  );
  assert.equal(cache.read(key).entry.result.matches[0].build, 'GRCh37');
  await validateLookup(lookup, 'GRCh37', 'catalog', { sha256: 'a'.repeat(64) });
  await assert.rejects(validateLookup(lookup, 'GRCh38', 'catalog', { sha256: 'a'.repeat(64) }));
  await assert.rejects(validateLookup(lookup, 'GRCh37', 'catalog', { sha256: 'b'.repeat(64) }));
});

